#!/usr/bin/env python3
"""Build the public site.

Reads the single-file practical pages from SRC (default: src/),
wraps each one as a complete standalone HTML document with a trilingual navigation bar
(home · previous · next), writes them to practicals/, and generates assets/practicals.js
with the trilingual titles and aims used by the home page.

    python3 tools/build_site.py [SRC_DIR]
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "src")
META = json.load(open(os.path.join(ROOT, "tools", "meta.json"), encoding="utf-8"))

UNITS = {
    1: ["Atomic structure", "පරමාණුක ව්‍යුහය", "அணுக் கட்டமைப்பு"],
    2: ["Structure and bonding", "ව්‍යුහය සහ බන්ධන", "கட்டமைப்பும் பிணைப்பும்"],
    3: ["Chemical calculations", "රසායනික ගණනය කිරීම්", "இரசாயனக் கணித்தல்கள்"],
    4: ["Gaseous state", "වායු අවස්ථාව", "வாயு நிலை"],
    5: ["Energetics", "ශක්ති විද්‍යාව", "சக்தியியல்"],
    6: ["s, p and d block", "s, p සහ d ගොනුව", "s, p, d தொகுதி"],
}
EXTRA = {"kmno4-titration.html": 3, "cu-complex-ions.html": 6}
AIM_FIX = {"kmno4-titration.html": [
    "Standardise a KMnO₄ solution by titrating it against a standard Fe²⁺ solution (KMnO₄ is its own indicator).",
    "සම්මත Fe²⁺ ද්‍රාවණයකට එරෙහිව අනුමාපනය කර KMnO₄ ද්‍රාවණයක් සම්මත කිරීම (KMnO₄ ස්ව-දර්ශකයකි).",
    "நியம Fe²⁺ கரைசலுடன் நியமித்து KMnO₄ கரைசலை நியமமாக்கல் (KMnO₄ சுயகாட்டி)."]}
TAGS = {  # short "what you will see" tags, en / si / ta
    "titration": ["Titration", "අනුමාපනය", "நியமிப்பு"], "colour": ["Colour changes", "වර්ණ වෙනස්", "நிற மாற்றங்கள்"],
    "gas": ["Gas tests", "වායු පරීක්ෂා", "வாயுச் சோதனைகள்"], "heat": ["Heating", "රත් කිරීම", "சூடாக்கல்"],
    "measure": ["Measurement", "මිනුම්", "அளவீடு"], "model": ["3D / models", "ආකෘති", "மாதிரிகள்"], "ppt": ["Precipitates", "අවක්ෂේප", "வீழ்படிவுகள்"],
}
FILE_TAGS = {
    "cathode-rays.html": ["model"], "vsepr-shapes.html": ["model"], "glassware-balance.html": ["measure"], "standard-solutions.html": ["measure"],
    "molar-volume.html": ["gas", "measure"], "magnesium-ar.html": ["gas", "measure"], "enthalpy-neutralisation.html": ["measure", "heat"], "hess-law.html": ["measure"],
    "s-block-metals.html": ["colour", "gas"], "flame-tests.html": ["colour", "heat"], "anion-tests.html": ["ppt", "gas", "colour"], "nitrogen-air.html": ["heat", "gas", "colour"],
    "halide-tests.html": ["ppt", "colour"], "thiosulphate-titration.html": ["titration", "colour"], "ammonia-tests.html": ["gas", "colour"], "solubility-spot-plate.html": ["ppt", "colour"],
    "thermal-stability.html": ["heat", "gas"], "d-block-colours.html": ["colour", "model"], "fe-kmno4-titration.html": ["titration", "colour"], "oxalate-kmno4.html": ["titration", "heat"],
    "kmno4-titration.html": ["titration", "colour"], "cu-complex-ions.html": ["colour", "ppt"],
}

def unit_of(m):
    if m["file"] in EXTRA: return EXTRA[m["file"]]
    u = re.search(r"Unit 0?(\d+)", m["eyebrow"]); return int(u.group(1))

items = []
for m in META:
    items.append({
        "file": m["file"], "id": m["id"], "exp": m["exp"], "unit": unit_of(m), "extra": m["exp"] is None,
        "title": m["title"], "aim": AIM_FIX.get(m["file"], m["aim"]), "tags": FILE_TAGS.get(m["file"], []),
    })
items.sort(key=lambda x: (x["exp"] is None, x["exp"] or 0, x["unit"]))

os.makedirs(os.path.join(ROOT, "assets"), exist_ok=True)
with open(os.path.join(ROOT, "assets", "practicals.js"), "w", encoding="utf-8") as f:
    f.write("// Generated by tools/build_site.py: list of practicals with trilingual titles and aims [en, si, ta]\n")
    f.write("window.SVL_UNITS = " + json.dumps(UNITS, ensure_ascii=False) + ";\n")
    f.write("window.SVL_TAGS = " + json.dumps(TAGS, ensure_ascii=False) + ";\n")
    f.write("window.SVL_PRACTICALS = " + json.dumps(items, ensure_ascii=False, indent=1) + ";\n")

HEAD = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="description" content="{desc}">
<link rel="icon" href="../assets/favicon.svg" type="image/svg+xml">
<style>
:root{{color-scheme:light;padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}}
body{{margin:0;font:14px/1.45 system-ui,-apple-system,"Segoe UI",Roboto,sans-serif}}
img{{max-width:100%}}
[hidden]{{display:none!important}}
.svlnav{{position:sticky;top:env(safe-area-inset-top,0px);z-index:40;background:#0E1A2B;background-image:linear-gradient(rgba(255,255,255,.055) 1px,transparent 1px),linear-gradient(90deg,rgba(255,255,255,.055) 1px,transparent 1px);background-size:28px 28px;color:#F4F1EA;font:500 14px/1.2 "IBM Plex Sans","Noto Sans Sinhala","Noto Sans Tamil",system-ui,sans-serif}}
.svlnav .in{{max-width:1400px;margin:0 auto;display:flex;align-items:center;gap:10px;flex-wrap:wrap;padding-block:8px;padding-left:max(16px,env(safe-area-inset-left,0px));padding-right:max(16px,env(safe-area-inset-right,0px))}}
.svlnav a{{color:#F4F1EA;text-decoration:none;display:inline-flex;align-items:center;gap:6px;min-height:36px;padding:0 12px;border:1.5px solid rgba(212,196,255,.45);border-radius:999px}}
.svlnav a:hover{{background:rgba(212,196,255,.14)}}
.svlnav a:focus-visible{{outline:3px solid #FFC857;outline-offset:2px}}
.svlnav .pos{{color:#D4C4FF;font-family:"IBM Plex Mono",ui-monospace,monospace;font-size:12px;margin-left:auto}}
.svlnav .pn{{display:flex;gap:8px}}
@media (max-width:560px){{.svlnav .lbl{{display:none}}.svlnav .pos{{margin-left:0}}}}
</style>
"""
NAV = """<nav class="svlnav" aria-label="Practicals">
<div class="in"><a href="../index.html#practicals">← <span data-svlnav="home">A/L labs</span></a>
<span class="pos">{pos}</span>
<span class="pn">{prev}{next}</span></div>
</nav>
<script>
(function(){{var L={{en:{{home:"All practicals",prev:"Previous",next:"Next"}},si:{{home:"සියලු ප්‍රායෝගික",prev:"පෙර",next:"ඊළඟ"}},ta:{{home:"எல்லாச் செய்முறைகளும்",prev:"முந்தையது",next:"அடுத்தது"}}}};
function lang(){{try{{var l=localStorage.getItem("svl-lang");if(L[l])return l;}}catch(e){{}}return "en";}}
function apply(){{var l=lang();document.querySelectorAll("[data-svlnav]").forEach(function(e){{e.textContent=L[l][e.getAttribute("data-svlnav")];}});}}
apply();document.addEventListener("click",function(){{setTimeout(apply,60);}});}})();
</script>
"""

for i, it in enumerate(items):
    src = open(os.path.join(SRC, it["file"]), encoding="utf-8").read()
    src = "\n".join(l for l in src.split("\n") if "svltest" not in l)
    cut = src.index("</style>") + len("</style>")
    head, body = src[:cut], src[cut:]
    prev_it = items[i - 1] if i > 0 else None
    next_it = items[i + 1] if i + 1 < len(items) else None
    lab = lambda x: ("Exp " + str(x["exp"])) if x["exp"] else "Extra"
    prev = f'<a href="{prev_it["file"]}" rel="prev">‹ <span class="lbl" data-svlnav="prev">Previous</span></a>' if prev_it else ""
    nxt = f'<a href="{next_it["file"]}" rel="next"><span class="lbl" data-svlnav="next">Next</span> ›</a>' if next_it else ""
    pos = f'{lab(it)} · {i + 1} / {len(items)}'
    desc = it["aim"][0] if it["aim"] else it["title"][0]
    page = HEAD.format(desc=desc.replace('"', "&quot;")) + head + "\n</head>\n<body>\n" + NAV.format(pos=pos, prev=prev, next=nxt) + body + "\n</body>\n</html>\n"
    open(os.path.join(ROOT, "practicals", it["file"]), "w", encoding="utf-8").write(page)
print("built", len(items), "practicals")
